/* Scaled score at study scores 20, 25, 30, 35, 40, 45, 50 (rounded, as VTAC prints them). */
export const SCALE_POINTS = [20, 25, 30, 35, 40, 45, 50];
export const SCALING = {
  eng: [17, 22, 28, 33, 39, 45, 50],
  mm:  [21, 28, 35, 41, 46, 49, 51],
  phy: [20, 26, 32, 37, 42, 47, 50],
  sd:  [17, 22, 28, 33, 39, 45, 50],
  ind: [26, 32, 38, 42, 46, 49, 52],
  eco: [20, 26, 31, 37, 42, 46, 50],
};

export function scaleScore(subId, raw) {
  const curve = SCALING[subId];
  if (!curve || !raw) return 0;
  const r = Math.min(50, raw);
  if (r <= SCALE_POINTS[0]) return Math.round(curve[0] * (r / SCALE_POINTS[0]) * 10) / 10;
  for (let i = 0; i < SCALE_POINTS.length - 1; i++) {
    if (r >= SCALE_POINTS[i] && r <= SCALE_POINTS[i + 1]) {
      const t = (r - SCALE_POINTS[i]) / (SCALE_POINTS[i + 1] - SCALE_POINTS[i]);
      return Math.round((curve[i] + t * (curve[i + 1] - curve[i])) * 10) / 10;
    }
  }
  return curve[curve.length - 1];
}

